import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Documents that the column the annotated attribute maps is an identity column, and how the database
 * generates its value.
 * <p>
 * {@link jakarta.persistence.GeneratedValue @GeneratedValue(strategy = IDENTITY)} says that the
 * database generates the value; it does not say whether an {@code INSERT} may supply one, which is what
 * this annotation documents.
 *
 * @see <a href="https://docs.oracle.com/en/database/oracle/oracle-database/23/sqlrf/CREATE-TABLE.html">CREATE TABLE (identity_clause)</a>
 */
@Documented
@Target(ElementType.FIELD)
@Retention(RetentionPolicy.SOURCE)
public @interface OraIdentity {

    /**
     * When the database generates the value of an identity column.
     */
    enum Generation {

        /**
         * {@code GENERATED ALWAYS}; an {@code INSERT} or {@code UPDATE} may not write the column.
         */
        ALWAYS,

        /**
         * {@code GENERATED BY DEFAULT}; the database generates the value when an {@code INSERT} leaves
         * the column out.
         */
        BY_DEFAULT,

        /**
         * {@code GENERATED BY DEFAULT ON NULL}; the database also generates the value when an
         * {@code INSERT} supplies {@code NULL}.
         */
        BY_DEFAULT_ON_NULL
    }

    /**
     * When the database generates the value.
     *
     * @return when the database generates the value.
     */
    Generation value() default Generation.ALWAYS;
}
